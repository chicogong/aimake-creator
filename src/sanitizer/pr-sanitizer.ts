import type { DeckDocument, SanitizeReport } from '../schema/types.js';

interface PatternRule {
  type: SanitizeReport['findings'][number]['type'];
  regex: RegExp;
  replacement: string;
}

const PRIVACY_RULES: PatternRule[] = [
  {
    type: 'token',
    regex: /\b(?:sk-[a-zA-Z0-9_-]{16,}|ghp_[a-zA-Z0-9]{20,}|gho_[a-zA-Z0-9]{20,}|AKID[a-zA-Z0-9]{16,}|xox[baprs]-[a-zA-Z0-9-]{16,}|eyJ[a-zA-Z0-9_-]{15,}\.eyJ[a-zA-Z0-9_-]{15,}\.[a-zA-Z0-9_-]{10,})\b/g,
    replacement: '<REDACTED_SECRET_TOKEN>',
  },
  {
    type: 'email',
    regex: /\b[a-zA-Z0-9._%+-]+@(?!example\.com\b)[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}\b/g,
    replacement: 'creator@example.com',
  },
  {
    type: 'internal_domain',
    regex: /https?:\/\/[a-zA-Z0-9.-]*\.(?:woa\.com|oa\.com|internal|corp\.[a-z]+|intranet|local)(?::\d+)?(?:\/[^\s)"']*)?/gi,
    replacement: 'https://internal.example.com/redacted',
  },
  {
    type: 'internal_domain',
    regex: /\b[a-zA-Z0-9.-]+\.(?:woa\.com|oa\.com|internal|intranet)\b/gi,
    replacement: 'internal.example.com',
  },
  {
    type: 'local_path',
    regex: /(?:\/Users\/[a-zA-Z0-9._-]+\/[^\s)"'`]+|\/home\/[a-zA-Z0-9._-]+\/[^\s)"'`]+|[A-Z]:\\Users\\[a-zA-Z0-9._-]+\\[^\s)"'`]+)/g,
    replacement: '~/workspace/project-fixture',
  },
  {
    type: 'ip_address',
    regex: /\b(?:10\.\d{1,3}\.\d{1,3}\.\d{1,3}|192\.168\.\d{1,3}\.\d{1,3}|172\.(?:1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3})\b/g,
    replacement: '10.0.0.1',
  },
  {
    type: 'phone',
    regex: /(?<!\d)1[3-9]\d{9}(?!\d)/g,
    replacement: '13800000000',
  },
];

export function sanitizeContentForPR(content: string): SanitizeReport {
  let working = content;
  const findings: SanitizeReport['findings'] = [];

  for (const rule of PRIVACY_RULES) {
    working = working.replace(rule.regex, (matched) => {
      const preview =
        matched.length > 12 ? `${matched.slice(0, 6)}...${matched.slice(-4)}` : '***';
      findings.push({
        type: rule.type,
        originalPreview: preview,
        replacement: rule.replacement,
      });
      return rule.replacement;
    });
  }

  return {
    clean: findings.length === 0,
    redactedCount: findings.length,
    findings,
    sanitizedContent: working,
  };
}

/**
 * Replaces sensitive business text inside a DeckDocument with synthetic structural mock data
 * so users can safely contribute a custom template layout via GitHub PR with zero corporate leakage.
 */
export function anonymizeDeckToSyntheticMock(doc: DeckDocument): DeckDocument {
  const mock: DeckDocument = structuredClone(doc);
  mock.frontmatter.title = 'Synthetic Architecture & Growth Review';
  mock.frontmatter.author = mock.frontmatter.author || 'Aimake Contributor';
  mock.frontmatter.handle = mock.frontmatter.handle || '@creator';
  mock.sourcePath = undefined;

  mock.slides = mock.slides.map((slide, idx) => ({
    ...slide,
    id: `mock-slide-${idx + 1}`,
    eyebrow: slide.eyebrow ? `MODULE 0${idx + 1}` : undefined,
    title:
      idx === 0
        ? 'How Local-First Workflows Compound Knowledge'
        : `Key Structural Insight #${idx}`,
    subtitle: slide.subtitle ? 'Synthetic benchmark fixture for template preview' : undefined,
    bullets: slide.bullets.map(
      (_, bIdx) => `Synthetic key point ${bIdx + 1}: replace raw repetition with reusable templates.`
    ),
    bodyParagraphs: slide.bodyParagraphs.map(
      () => 'This is synthetic sample copy generated by Aimake PR Sanitizer so private notes never leave your machine.'
    ),
    metrics: slide.metrics.map((m, mIdx) => ({
      label: `Metric ${mIdx + 1}`,
      value: `${(mIdx + 1) * 42}%`,
      delta: m.delta ? '+18%' : undefined,
    })),
    quote: slide.quote
      ? {
          text: 'Design is how structured knowledge becomes unmistakable.',
          author: 'Synthetic Reference',
        }
      : undefined,
    comparison: slide.comparison
      ? {
          leftTitle: 'Before (Ad-hoc)',
          leftItems: ['Scattered prompts', 'Manual layout tweaks'],
          rightTitle: 'After (Systematized)',
          rightItems: ['Grounded Wiki memory', 'One-click multi-format export'],
        }
      : undefined,
    code: slide.code
      ? {
          lang: slide.code.lang,
          code: '// Synthetic code sample\nexport const compile = (deck) => render(deck);',
        }
      : undefined,
    cite: slide.cite ? 'wiki/synthetic-reference.md#L10' : undefined,
    speech: slide.speech ? 'Synthetic narration line for motion preview.' : undefined,
  }));

  return mock;
}
